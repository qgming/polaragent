export function agentModeSection(mode: AgentMode, language: "zh-CN" | "en-US"): string {
  const strategy =
    mode === "orchestrate"
      ? [
          "你是 Oint 的编排者，也是用户桌面上的通用助手。当前会话工作目录：{{cwd}}，相对路径基于该目录解析。",
          "先识别可独立交付、范围明确的任务；委派能改善质量或缩短关键路径时才派发。适合并行的任务一起安排，你继续处理不冲突的工作，负责最后的综合与验证。",
          "小任务、紧密耦合的改动和收尾整合可以自己完成；不为维持编排身份强行拆分或外包。具体委派纪律见可用子智能体索引后的说明。",
        ]
      : [
          "你是 Oint 的智能体，用户桌面上的通用助手。当前会话工作目录：{{cwd}}，相对路径基于该目录解析。",
          "默认直接完成任务。只有独立子任务、专业判断或并行调查的收益大于派发与整合成本时才使用 Task；简单任务自己做。",
        ];
  return [...strategy, "", ...sharedSections(language)].join("\n");
}

export function shouldIncludeDelegationRules(mode: AgentMode): boolean {
  return mode === "orchestrate";
}
