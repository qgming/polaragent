/**
 * 项目：侧栏「项目」分组里的一个绑定文件夹。
 *
 * 绑定关系不写在会话上，而是**由会话的 cwd 反推**：
 * 会话工作目录落在某个项目目录内（含其本身）就归到该项目，
 * 没落在任何项目里的会话留在「最近」。这样绑定/解绑只动一份项目列表，
 * 不会因为漏写某个会话的字段而出现「会话在两处都在 / 都不在」。
 */
export interface Project {
  id: string;
  /** 展示名：默认取目录名，用户在界面里看不到完整路径时也能认出来 */
  name: string;
  /** 绑定的绝对路径（目录） */
  path: string;
  createdAt: number;
}
